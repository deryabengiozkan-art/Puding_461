def glyph(ch, bold=False):
    ch = {'i': 'I', 'ı': 'I', 'ç': 'Ç', 'ğ': 'Ğ', 'ö': 'Ö', 'ş': 'Ş', 'ü': 'Ü'}.get(ch, ch.upper())
    if ch not in G and ch not in BOLD:
        ch = '?'
    if bold and ch in BOLD:
        w = len(BOLD[ch][0])
        return np.array([[c == '#' for c in r] for r in ['.' * w] * 2 + BOLD[ch]], bool)
    rows = G.get(ch, G['?'])
    a = np.array([[c == '#' for c in r] for r in rows], bool)
    t = TRIM.get(ch, 0)
    a = a[:, t:t + ADV.get(ch, 6) - 1] if ch in ADV else a
    if bold:
        b = np.zeros((a.shape[0], a.shape[1] + 1), bool)
        b[:, :-1] |= a; b[:, 1:] |= a
        a = b
    return a



def _normal(text):
    out = []
    for ch in str(text):
        out.append(ALIAS.get(ch, ch))
    return ''.join(out)


def mask(text, bold=False, spacing=1):
    gl = [glyph(c, bold) for c in _normal(text)]
    w = sum(x.shape[1] for x in gl) + spacing * max(0, len(gl) - 1)
    m = np.zeros((9, max(1, w)), bool)
    x = 0
    for a in gl:
        m[:, x:x + a.shape[1]] |= a
        x += a.shape[1] + spacing
    return m


def render(text, fill=(255, 245, 220), bold=True, outline=INK, outline_w=1,
           shadow=1, grad=None, spacing=1, inner_hi=False):
    """Native-size text surface. grad=(top, bottom) gives the two-tone title look."""
    m = mask(text, bold, spacing)
    H, W = m.shape[0] + 2 * outline_w + shadow, m.shape[1] + 2 * outline_w
    img = np.zeros((H, W, 4), np.uint8)
    core = np.zeros((H, W), bool)
    core[outline_w:outline_w + m.shape[0], outline_w:outline_w + m.shape[1]] = m
    if outline is not None:
        o = core.copy()
        for _ in range(outline_w):
            n = o.copy()
            n[1:] |= o[:-1]; n[:-1] |= o[1:]; n[:, 1:] |= o[:, :-1]; n[:, :-1] |= o[:, 1:]
            o = n
        for s in range(shadow + 1):
            sh = np.zeros_like(o); sh[s:] = o[:H - s]
            img[sh] = rgba(outline)
    rows = np.where(core.any(1))[0]
    top, bot = (rows.min(), rows.max()) if len(rows) else (0, 1)
    for y in range(H):
        if grad:
            t = (y - top) / max(1, bot - top)
            c = rgba(grad[0]) if t < .5 else rgba(grad[1])
        else:
            c = rgba(fill)
        img[y][core[y]] = c
    if inner_hi:
        upm = np.zeros_like(core); upm[1:] = core[:-1]
        img[core & ~upm] = shade(grad[0] if grad else fill, .55)
    return from_array(img)


def width(text, bold=True, spacing=1):
    return mask(text, bold, spacing).shape[1] + 2


def wrap(words, max_w, bold=False):
    """Split a string into lines that fit ``max_w`` native pixels."""
    lines, cur = [], ''
    for word in str(words).split():
        test = (cur + ' ' + word).strip()
        if cur and width(test, bold) > max_w:
            lines.append(cur)
            cur = word
        else:
            cur = test
    if cur:
        lines.append(cur)
    return lines or ['']


_cache = OrderedDict()


def text(words, scale=1, **style):
    """Cached, scaled text surface."""
    key = (str(words), scale, tuple(sorted((k, str(v)) for k, v in style.items())))
    hit = _cache.get(key)
    if hit is not None:
        _cache.move_to_end(key)
        return hit
    surf = big(render(words, **style), scale)
    if pygame.display.get_init() and pygame.display.get_surface():
        surf = surf.convert_alpha()
    _cache[key] = surf
    if len(_cache) > 600:
        _cache.popitem(last=False)
    return surf
